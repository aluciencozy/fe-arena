import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ANILIST_GRAPHQL_URL = "https://graphql.anilist.co";
const OUTPUT_DIR = path.resolve("data");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "anilist-anime-candidates.json");
const OUTPUT_TS = path.join(OUTPUT_DIR, "anilist-anime-candidates.catalog.ts");

const LISTS = [
  { key: "popular", label: "Top 100 Popular", sort: "POPULARITY_DESC" },
  { key: "rated", label: "Top 100 Highest Rated", sort: "SCORE_DESC" },
];

const QUERY = `
  query AnimeCandidates($page: Int!, $perPage: Int!, $sort: [MediaSort]) {
    Page(page: $page, perPage: $perPage) {
      media(
        type: ANIME
        sort: $sort
        isAdult: false
        format_not: MUSIC
      ) {
        id
        idMal
        title {
          romaji
          english
          native
          userPreferred
        }
        coverImage {
          extraLarge
          large
          color
        }
        bannerImage
        averageScore
        popularity
        trending
        format
        status
        episodes
        seasonYear
        genres
        siteUrl
      }
    }
  }
`;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const slugify = (value) =>
  value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");

const fetchPage = async ({ sort, page, perPage }) => {
  const response = await fetch(ANILIST_GRAPHQL_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json",
    },
    body: JSON.stringify({
      query: QUERY,
      variables: { page, perPage, sort: [sort] },
    }),
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(
      `AniList request failed (${response.status} ${response.statusText}): ${body}`,
    );
  }

  const payload = await response.json();
  if (payload.errors) {
    throw new Error(JSON.stringify(payload.errors, null, 2));
  }

  return payload.data.Page.media;
};

const fetchTop100 = async (list) => {
  const perPage = 50;
  const pages = [1, 2];
  const results = [];

  for (const page of pages) {
    const media = await fetchPage({ sort: list.sort, page, perPage });
    results.push(...media);
    await sleep(750);
  }

  return results.slice(0, 100);
};

const toCandidate = (media, source) => ({
  id: `anilist-${media.id}-${slugify(media.title.userPreferred || media.title.romaji)}`,
  anilistId: media.id,
  malId: media.idMal,
  mode: "anime",
  name: media.title.english || media.title.romaji || media.title.userPreferred,
  romajiName: media.title.romaji,
  nativeName: media.title.native,
  coverImageUrl: media.coverImage.extraLarge || media.coverImage.large,
  bannerImageUrl: media.bannerImage,
  coverColor: media.coverImage.color,
  averageScore: media.averageScore,
  popularity: media.popularity,
  trending: media.trending,
  format: media.format,
  status: media.status,
  episodes: media.episodes,
  seasonYear: media.seasonYear,
  genres: media.genres,
  siteUrl: media.siteUrl,
  sources: [source],
  canonicalTitle: media.title.english || media.title.romaji || media.title.userPreferred,
  answerAliases: [],
  tracks: [],
});

const toTsCatalog = (items) => `// Generated by scripts/fetch-anilist-anime-candidates.mjs.
// Add YouTube track entries manually before wiring these into the playable catalog.

export const anilistAnimeCandidates = ${JSON.stringify(items, null, 2)} as const;
`;

const main = async () => {
  const byAniListId = new Map();
  const sourceCounts = {};

  for (const list of LISTS) {
    const entries = await fetchTop100(list);
    sourceCounts[list.key] = entries.length;

    for (const media of entries) {
      const existing = byAniListId.get(media.id);
      if (existing) {
        existing.sources.push(list.key);
      } else {
        byAniListId.set(media.id, toCandidate(media, list.key));
      }
    }
  }

  const candidates = [...byAniListId.values()].sort((a, b) => {
    const scoreA = Math.max(a.popularity ?? 0, a.trending ?? 0, a.averageScore ?? 0);
    const scoreB = Math.max(b.popularity ?? 0, b.trending ?? 0, b.averageScore ?? 0);
    return scoreB - scoreA;
  });

  const output = {
    generatedAt: new Date().toISOString(),
    source: "AniList GraphQL API",
    requestedLists: LISTS.map(({ key, label, sort }) => ({ key, label, sort })),
    sourceCounts,
    uniqueCount: candidates.length,
    candidates,
  };

  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(OUTPUT_JSON, `${JSON.stringify(output, null, 2)}\n`);
  await writeFile(OUTPUT_TS, toTsCatalog(candidates));

  console.log(`Fetched ${sourceCounts.popular} popular anime.`);
  console.log(`Fetched ${sourceCounts.rated} highest-rated anime.`);
  console.log(`Wrote ${candidates.length} unique candidates.`);
  console.log(`JSON: ${OUTPUT_JSON}`);
  console.log(`TS:   ${OUTPUT_TS}`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
